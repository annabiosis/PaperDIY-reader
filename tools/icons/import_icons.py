#!/usr/bin/env python3
"""Packs the exported Figma icons into a C++ atlas for the firmware.

Input:  ereader/icons/**/*.png  (RGBA, white shapes on transparent)
Output: firmware/main/ui/icons_atlas.cpp  (1-bit masks, used as tinted sprites)

The alpha channel is thresholded to 0/255: the panel draws these sprites in DU
(1 bit) for the file manager, and half-covered pixels would be dithered/noisy.

Naming is normalised:
  Icons/24/stroke/file.png                  -> file
  Icons/24/fill/folder.png                  -> folder_fill
  Icons/24/stroke/btn-A-B-hold.png          -> btn_a_b_hold
  Property ... bat, 100.png                 -> battery_100
  CURSOR.png                                -> cursor
"""

from __future__ import annotations

import pathlib
import re
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
ICONS = ROOT / "icons"
OUT_CPP = ROOT / "firmware" / "main" / "ui" / "icons_atlas.cpp"
OUT_H = ROOT / "firmware" / "main" / "ui" / "icons.h"
THRESHOLD = 128


def canonical(path: pathlib.Path) -> str:
    stem = path.stem.lower()
    parent = path.parent.name.lower()

    if "bat" in stem and "=" in stem:
        # Variant names look like "Property 1=24, ... Property 4=75"
        level = stem.split("=")[-1].strip()
        return f"battery_{level}"

    name = stem.replace("-", "_").replace(" ", "_")
    name = re.sub(r"[^a-z0-9_]", "", name)
    if name == "cursor":
        return "cursor"
    if parent == "fill":
        return f"{name}_fill"
    return name


def collect() -> list[tuple[str, pathlib.Path]]:
    entries = []
    for path in sorted(ICONS.rglob("*.png")):
        entries.append((canonical(path), path))
    seen = set()
    for name, path in entries:
        if name in seen:
            raise SystemExit(f"duplicate icon name '{name}' ({path})")
        seen.add(name)
    return entries


def mask_of(path: pathlib.Path) -> tuple[int, int, bytes]:
    image = Image.open(path).convert("RGBA")
    width, height = image.size
    alpha = image.getchannel("A")
    low, high = alpha.getextrema()
    if low == high:
        # Opaque export (black shape on white): use inverted luminance as coverage.
        luminance = image.convert("L")
        data = bytes(255 - value for value in luminance.getdata())
    else:
        data = bytes(255 if value >= THRESHOLD else 0 for value in alpha.getdata())
    return width, height, data


def format_bytes(data: bytes, per_line: int = 24) -> str:
    lines = []
    for i in range(0, len(data), per_line):
        lines.append("    " + ",".join(str(b) for b in data[i : i + per_line]) + ",")
    return "\n".join(lines)


def main() -> int:
    entries = collect()
    if not entries:
        raise SystemExit(f"no PNG files under {ICONS}")

    blocks = [
        "// Generated by tools/icons/import_icons.py - do not edit.",
        "// 1-bit masks from the Figma icon set (alpha thresholded).",
        '#include "ui/icons.h"',
        "",
        "namespace reader {",
        "namespace {",
        "",
    ]
    table = []
    for name, path in entries:
        width, height, data = mask_of(path)
        ident = f"icon_{name}"
        blocks.append(f"const unsigned char {ident}[] = {{")
        blocks.append(format_bytes(data))
        blocks.append("};")
        table.append((name, ident, width, height))
        print(f"{name:<20} {width}x{height}  {len(data)} bytes")

    blocks.append("")
    blocks.append("}  // namespace")
    blocks.append("")
    blocks.append("extern const IconData kIcons[];")
    blocks.append("extern const size_t kIconCount;")
    blocks.append("")
    blocks.append("const IconData kIcons[] = {")
    for name, ident, width, height in table:
        blocks.append(f'    {{"{name}", {width}, {height}, {ident}}},')
    blocks.append("};")
    blocks.append(f"const size_t kIconCount = {len(table)};")
    blocks.append("")
    blocks.append("}  // namespace reader")
    blocks.append("")
    OUT_CPP.write_text("\n".join(blocks), encoding="utf-8", newline="\n")

    header = """// Icon sprites exported from the Figma set (24x24, 1-bit masks).
#pragma once

#include <cstddef>
#include <cstdint>

namespace reader {

struct IconData {
    const char* name;
    uint8_t width;
    uint8_t height;
    const uint8_t* pixels; // 0 or 255 per pixel, row-major
};

extern const IconData kIcons[];
extern const size_t kIconCount;

// Looks up an icon by name; returns nullptr when the name is unknown.
const IconData* find_icon(const char* name);

} // namespace reader
"""
    OUT_H.write_text(header, encoding="utf-8", newline="\n")
    print(f"\nwrote {OUT_CPP} ({len(table)} icons)")
    print(f"wrote {OUT_H}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
